def assemble_cloth_hamiltonian(
    state: IntrinsicClothPhaseState,
    membrane_energy: Tensor,
    bending_energy: Tensor,
    *,
    gravity_m_s2: tuple[float, float, float] = (0.0, -9.81, 0.0),
    contact_barrier_energy: Tensor | None = None,
    metric_constraint_energy: Tensor | None = None,
) -> ClothHamiltonian:
    """Assemble the audited conservative Hamiltonian in SI coordinates."""

    membrane = membrane_energy.sum()
    bending = bending_energy.sum()
    gravity_vector = state.positions.new_tensor(gravity_m_s2)
    gravity = -(state.lumped_mass[:, None] * gravity_vector * state.positions).sum()
    contact = (
        state.positions.new_zeros(())
        if contact_barrier_energy is None
        else contact_barrier_energy
    )
    if contact.ndim != 0:
        raise ValueError("contact barrier energy must be scalar")
    metric = (
        state.positions.new_zeros(())
        if metric_constraint_energy is None
        else metric_constraint_energy
    )
    if metric.ndim != 0:
        raise ValueError("metric constraint energy must be scalar")
    kinetic = state.kinetic_energy()
    return ClothHamiltonian(
        total=kinetic + membrane + bending + gravity + contact + metric,
        kinetic=kinetic,
        membrane=membrane,
        bending=bending,
        gravity=gravity,
        contact_barrier=contact,
        metric_constraint=metric,
    )


def metric_strain_barrier_energy(
    positions: Tensor,
    edges: Tensor,
    rest_lengths: Tensor,
    *,
    maximum_tensile_strain: float,
    maximum_compressive_strain: float,
    barrier_scale_j: float = 1.0e-4,
) -> Tensor:
    """Training surrogate for the hard feasible-set indicator in ``H_c``."""

    if edges.ndim != 2 or edges.shape[1] != 2 or rest_lengths.shape != (len(edges),):
        raise ValueError("metric edges and rest lengths have incompatible shape")
    if barrier_scale_j <= 0.0:
        raise ValueError("metric barrier scale must be positive")
    edge = edges.to(device=positions.device, dtype=torch.long)
    rest = rest_lengths.to(positions).clamp_min(1.0e-8)
    length = torch.linalg.vector_norm(
        positions[edge[:, 1]] - positions[edge[:, 0]], dim=-1
    )
    strain = length / rest - 1.0
    violation = F.relu(strain - maximum_tensile_strain) + F.relu(
        -maximum_compressive_strain - strain
    )
    return barrier_scale_j * violation.square().sum()


@dataclass(frozen=True)
class VariationalPhasePINNConfig:
    """Scales for a discrete Hamilton-d'Alembert cloth residual."""

    force_scale_n: float = 2.0e-3
    power_scale_w: float = 2.0e-3
    contact_clearance_m: float = 0.003
    contact_stiffness_n_m: float = 600.0
    contact_smoothing_m: float = 2.5e-4
    velocity_damping_n_s_m: float = 0.02
    friction_coefficient: float = 0.35
    friction_velocity_m_s: float = 0.02
    action_stationarity_weight: float = 1.0
    energy_balance_weight: float = 0.1
    contact_kkt_weight: float = 0.25
    dissipation_weight: float = 0.1
    metric_constraint_weight: float = 0.25
    metric_energy_scale_j: float = 1.0e-4

    def __post_init__(self) -> None:
        positive = (
            self.force_scale_n,
            self.power_scale_w,
            self.contact_stiffness_n_m,
            self.contact_smoothing_m,
            self.friction_velocity_m_s,
            self.metric_energy_scale_j,
        )
        if any(value <= 0.0 for value in positive):
            raise ValueError("PINN force, power, contact, and velocity scales must be positive")
        nonnegative = (
            self.contact_clearance_m,
            self.velocity_damping_n_s_m,
            self.friction_coefficient,
            self.action_stationarity_weight,
            self.energy_balance_weight,
            self.contact_kkt_weight,
            self.dissipation_weight,
            self.metric_constraint_weight,
        )
        if any(value < 0.0 for value in nonnegative):
            raise ValueError("PINN clearances, material coefficients, and weights must be non-negative")


@dataclass(frozen=True)
class VariationalPhasePINNResidual:
    total: Tensor
    action_stationarity: Tensor
    energy_balance: Tensor
    contact_kkt: Tensor
    dissipation: Tensor
    metric_constraint: Tensor
    momentum_residual: Tensor
    contact_force: Tensor
    friction_force: Tensor
    damping_force: Tensor
    contact_multiplier: Tensor
    discrete_lagrangian: Tensor

    def detached_metrics(self) -> dict[str, float]:
        return {
            "total": float(self.total.detach()),
            "action_stationarity": float(self.action_stationarity.detach()),
            "energy_balance": float(self.energy_balance.detach()),
            "contact_kkt": float(self.contact_kkt.detach()),
            "dissipation": float(self.dissipation.detach()),
            "metric_constraint": float(self.metric_constraint.detach()),
        }


def variational_phase_pinn_residual(
    previous_positions: Tensor,
    current_positions: Tensor,
    next_positions: Tensor,
    lumped_mass: Tensor,
    conservative_internal_force: Tensor,
    potential_energy: Tensor,
    *,
    dt: float,
    external_force: Tensor | None = None,
    contact_gap: Tensor | None = None,
    contact_normals: Tensor | None = None,
    body_velocities: Tensor | None = None,
    hierarchy_weight: Tensor | None = None,
    metric_constraint_energy: Tensor | None = None,
    config: VariationalPhasePINNConfig = VariationalPhasePINNConfig(),
) -> VariationalPhasePINNResidual:
    """Evaluate an E(3)-invariant variational PINN residual on one cloth phase.

    The stationarity term is the discrete Euler-Lagrange equation with
    d'Alembert forces. Contact uses a smooth non-negative SDF multiplier and
    KKT residual; damping and Coulomb friction enter through a dissipation
    potential rather than being folded into the conservative Hamiltonian.
    """

    if dt <= 0.0:
        raise ValueError("phase time step must be positive")
    shape = current_positions.shape
    if current_positions.ndim != 2 or shape[1] != 3:
        raise ValueError("phase positions must have shape (V,3)")
    if previous_positions.shape != shape or next_positions.shape != shape:
        raise ValueError("three phase samples must have matching shapes")
    if conservative_internal_force.shape != shape:
        raise ValueError("conservative internal force must match phase positions")
    if lumped_mass.shape != (len(current_positions),) or torch.any(lumped_mass <= 0.0):
        raise ValueError("lumped mass must be positive with shape (V,)")
    if potential_energy.ndim != 0:
        raise ValueError("potential energy must be scalar")

    mass = lumped_mass.to(current_positions)
    velocity_before = (current_positions - previous_positions) / dt
    velocity_after = (next_positions - current_positions) / dt
    midpoint_velocity = 0.5 * (velocity_before + velocity_after)
    momentum_before = mass[:, None] * velocity_before
    momentum_after = mass[:, None] * velocity_after

    applied = torch.zeros_like(current_positions)
    if external_force is not None:
        if external_force.shape == (3,):
            applied = external_force.to(current_positions)[None, :].expand_as(current_positions)
        elif external_force.shape == shape:
            applied = external_force.to(current_positions)
        else:
            raise ValueError("external force must have shape (3,) or (V,3)")

    damping_force = -config.velocity_damping_n_s_m * midpoint_velocity
    contact_force = torch.zeros_like(current_positions)
    friction_force = torch.zeros_like(current_positions)
    multiplier = current_positions.new_zeros(len(current_positions))
    penetration = current_positions.new_zeros(len(current_positions))
    complementarity = current_positions.new_zeros(len(current_positions))
    if contact_gap is not None or contact_normals is not None:
        if contact_gap is None or contact_normals is None:
            raise ValueError("contact gap and normals must be supplied together")
        if contact_gap.shape != (len(current_positions),) or contact_normals.shape != shape:
            raise ValueError("contact gap and normals have incompatible shape")
        normal = F.normalize(contact_normals.to(current_positions), dim=-1, eps=1.0e-8)
        feasible_gap = contact_gap.to(current_positions) - config.contact_clearance_m
        penetration = F.relu(-feasible_gap)
        multiplier = config.contact_stiffness_n_m * config.contact_smoothing_m * F.softplus(
            -feasible_gap / config.contact_smoothing_m
        )
        contact_force = multiplier[:, None] * normal
        body_velocity = (
            torch.zeros_like(current_positions)
            if body_velocities is None
            else body_velocities.to(current_positions)
        )
        if body_velocity.shape != shape:
            raise ValueError("body velocities must match phase positions")
        relative_velocity = midpoint_velocity - body_velocity
        tangent_velocity = relative_velocity - (
            relative_velocity * normal
        ).sum(dim=-1, keepdim=True) * normal
        tangent_speed = torch.linalg.vector_norm(tangent_velocity, dim=-1).clamp_min(1.0e-9)
        regularized_direction = tangent_velocity / tangent_speed[:, None]
        friction_force = -(
            config.friction_coefficient
            * multiplier
            * torch.tanh(tangent_speed / config.friction_velocity_m_s)
        )[:, None] * regularized_direction
        # Fischer-Burmeister is zero exactly when lambda >= 0, gap >= 0,
        # and lambda * gap = 0.
        scaled_multiplier = multiplier / config.force_scale_n
        scaled_gap = feasible_gap / config.contact_smoothing_m
        complementarity = torch.sqrt(
            scaled_multiplier.square() + scaled_gap.square() + 1.0e-12
        ) - scaled_multiplier - scaled_gap

    total_force = (
        conservative_internal_force
        + applied
        + contact_force
        + friction_force
        + damping_force
    )
    momentum_residual = (momentum_after - momentum_before) / dt - total_force
    weight = (
        torch.ones_like(mass)
        if hierarchy_weight is None
        else hierarchy_weight.to(current_positions)
    )
    if weight.shape != mass.shape or torch.any(weight < 0.0):
        raise ValueError("hierarchy weight must be non-negative with shape (V,)")
    normalizer = weight.sum().clamp_min(1.0)
    action_stationarity = (
        weight * _pseudo_huber_norm(momentum_residual / config.force_scale_n)
    ).sum() / normalizer

    kinetic_before = 0.5 * (mass[:, None] * velocity_before.square()).sum()
    kinetic_after = 0.5 * (mass[:, None] * velocity_after.square()).sum()
    conservative_power = (conservative_internal_force * midpoint_velocity).sum()
    applied_power = (applied * midpoint_velocity).sum()
    contact_power = (contact_force * midpoint_velocity).sum()
    dissipative_power = ((friction_force + damping_force) * midpoint_velocity).sum()
    energy_rate_residual = (
        (kinetic_after - kinetic_before) / dt
        - conservative_power
        - applied_power
        - contact_power
        - dissipative_power
    )
    energy_balance = _pseudo_huber_scalar(
        energy_rate_residual / config.power_scale_w
    )
    contact_kkt = (
        (penetration / max(config.contact_clearance_m, 1.0e-6)).square().mean()
        + complementarity.square().mean()
    )
    dissipation = F.relu(dissipative_power / config.power_scale_w).square()
    metric_constraint = (
        current_positions.new_zeros(())
        if metric_constraint_energy is None
        else metric_constraint_energy / config.metric_energy_scale_j
    )
    if metric_constraint.ndim != 0:
        raise ValueError("metric constraint energy must be scalar")
    discrete_lagrangian = dt * (
        0.5 * (mass[:, None] * midpoint_velocity.square()).sum() - potential_energy
    )
    total = (
        config.action_stationarity_weight * action_stationarity
        + config.energy_balance_weight * energy_balance
        + config.contact_kkt_weight * contact_kkt
        + config.dissipation_weight * dissipation
        + config.metric_constraint_weight * metric_constraint
    )
    return VariationalPhasePINNResidual(
        total=total,
        action_stationarity=action_stationarity,
        energy_balance=energy_balance,
        contact_kkt=contact_kkt,
        dissipation=dissipation,
        metric_constraint=metric_constraint,
        momentum_residual=momentum_residual,
        contact_force=contact_force,
        friction_force=friction_force,
        damping_force=damping_force,
        contact_multiplier=multiplier,
        discrete_lagrangian=discrete_lagrangian,
    )


def _pseudo_huber_norm(value: Tensor) -> Tensor:
    squared_norm = value.square().sum(dim=-1)
    return torch.sqrt(1.0 + squared_norm) - 1.0


def _pseudo_huber_scalar(value: Tensor) -> Tensor:
    return torch.sqrt(1.0 + value.square()) - 1.0
