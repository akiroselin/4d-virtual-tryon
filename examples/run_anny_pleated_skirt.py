from __future__ import annotations

import argparse
from dataclasses import replace
from pathlib import Path
import sys

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from aigc_fashion.anny_cloth4d_simulation import AnnyCloth4DConfig, run_anny_cloth4d_simulation  # noqa: E402
from aigc_fashion.body_mesh_avatar import BodyMeshAvatar  # noqa: E402
from aigc_fashion.data import AvatarSpec, MaterialSpec  # noqa: E402
from aigc_fashion.nyx_render import export_nyx_scene_assets  # noqa: E402
from aigc_fashion.pleated_skirt import (  # noqa: E402
    build_body_conditioned_pleated_skirt_shell,
    extract_plaid_texture,
    infer_pleated_skirt_spec,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Simulate an image-conditioned pleated skirt on Anny.")
    parser.add_argument("--image", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, default=ROOT / "outputs" / "anny_pleated_skirt")
    parser.add_argument("--body-mesh", type=Path, default=ROOT / "assets" / "body_meshes" / "anny_child_neutral.obj")
    parser.add_argument("--training-steps", type=int, default=100)
    parser.add_argument("--minimum-training-steps", type=int, default=60)
    parser.add_argument("--teacher-steps", type=int, default=18)
    parser.add_argument("--teacher-substeps-per-frame", type=int, default=5)
    parser.add_argument("--cortexode-steps", type=int, default=80)
    parser.add_argument("--cortexode-unet-steps", type=int, default=20)
    parser.add_argument(
        "--shell-reconstruction",
        choices=("cortexode", "direct"),
        default="cortexode",
    )
    parser.add_argument(
        "--teacher-rollout",
        type=Path,
        default=None,
        help="Reuse a validated physics teacher .npy and only retrain the 4D field.",
    )
    parser.add_argument(
        "--warm-start-checkpoint",
        type=Path,
        default=None,
        help="Continue the 4D field and Hyper-NODE material calibration from a checkpoint.",
    )
    parser.add_argument("--genesis-repo", type=Path, default=ROOT.parents[1] / "work" / "genesis-world")
    parser.add_argument(
        "--design2garmentcode-repo",
        type=Path,
        default=ROOT.parents[1] / "work" / "design2garmentcode",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    texture = extract_plaid_texture(args.image, args.out_dir / "image_conditioned_plaid.png")
    avatar_spec = AvatarSpec(chest_cm=64.0, waist_cm=56.0, shoulder_cm=30.0, height_cm=128.0, pose="a-pose")
    material = MaterialSpec(
        name="medium-heavy wool-blend plaid suiting",
        density=4.8,
        stretch_stiffness=18.0,
        bending_stiffness=2.6,
        damping=0.985,
        thickness=0.0015,
    )
    config = replace(
        AnnyCloth4DConfig(),
        teacher_steps=args.teacher_steps,
        teacher_substeps_per_frame=args.teacher_substeps_per_frame,
        training_steps=args.training_steps,
        minimum_training_steps=min(args.minimum_training_steps, args.training_steps),
        implicit_shell_target_faces=1800,
        cortexode_optimization_steps=args.cortexode_steps,
        cortexode_unet_steps=args.cortexode_unet_steps,
    )
    if args.warm_start_checkpoint is not None:
        checkpoint = torch.load(
            args.warm_start_checkpoint,
            map_location="cpu",
            weights_only=True,
        )
        source = checkpoint["config"]
        config = replace(
            config,
            intrinsic_channels=source["intrinsic_channels"],
            scene_feature_dim=source["scene_feature_dim"],
            material_latent_dim=source["material_latent_dim"],
            hidden_dim=source["hidden_dim"],
        )
    summary = run_anny_cloth4d_simulation(
        out_dir=args.out_dir,
        body_mesh=args.body_mesh,
        # The skirt runtime representation is generated by its garment-class
        # prior; this argument is retained for API compatibility and provenance.
        pattern_spec=ROOT / "examples" / "synthetic_learned_tshirt_spec.json",
        texture_image=texture,
        garment_image=args.image,
        warm_start_obj=None,
        genesis_repo=args.genesis_repo,
        design2garmentcode_repo=args.design2garmentcode_repo,
        simulation_topology="pleated_skirt_shell",
        shell_reconstruction_mode=args.shell_reconstruction,
        garment_kind="pleated_skirt",
        material_spec=material,
        avatar_spec=avatar_spec,
        teacher_rollout=args.teacher_rollout,
        warm_start_checkpoint=args.warm_start_checkpoint,
        config=config,
    )

    avatar = BodyMeshAvatar.from_obj(
        args.body_mesh,
        avatar_spec,
        source_up_axis="z",
        source_front_axis="-y",
    )
    garment, _ = build_body_conditioned_pleated_skirt_shell(
        avatar,
        infer_pleated_skirt_spec(args.image),
    )
    final_vertices = np.load(summary["artifacts"]["constrained_field_rollout"])[-1]
    nyx = export_nyx_scene_assets(
        args.out_dir / "nyx" / "assets",
        avatar,
        garment,
        final_vertices,
        texture,
    )
    print(f"simulation: {summary['status']}")
    print(f"animation: {summary['artifacts']['gif']}")
    print(f"final image: {summary['artifacts']['final_png']}")
    print(f"Nyx assets: {nyx['manifest']}")


if __name__ == "__main__":
    main()
